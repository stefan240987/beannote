def brew_method_label(method: str, lang: str | None = None) -> str:
    raw = (method or "").strip()
    if not raw:
        return ""
    key = BREW_METHOD_KEYS.get(raw) or BREW_METHOD_KEYS.get(raw.title())
    return t(normalize_lang(lang), key) if key else raw


def brew_method_i18n_table() -> dict[str, dict[str, str]]:
    table: dict[str, dict[str, str]] = {}
    for method, key in BREW_METHOD_KEYS.items():
        table[method] = {code: t(code, key) for code in LANGS}
        table[method.lower()] = table[method]
    return table
